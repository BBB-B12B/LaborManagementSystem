/**
 * sync-segment-engine.js
 *
 * Copies backend/src/services/reconciliation/segmentEngine.ts into
 * functions/src/segmentEngine.ts, so the Cloud Function build always uses the
 * exact same reconciliation logic as the Express backend.
 *
 * Why a copy instead of a shared package: `functions/` is deployed as a
 * standalone directory (Firebase only uploads `functions/`, see firebase.json
 * "source": "functions") and is not part of the root npm workspaces — it has no
 * access to `backend/`'s files at deploy time. This script runs as a `prebuild`
 * step (see functions/package.json) so the copy is always fresh before `tsc`.
 *
 * DO NOT hand-edit functions/src/segmentEngine.ts — edit
 * backend/src/services/reconciliation/segmentEngine.ts and re-run this script
 * (or just run `npm run build` in functions/, which does it automatically).
 */
const fs = require('fs');
const path = require('path');

const SRC = path.resolve(__dirname, '../backend/src/services/reconciliation/segmentEngine.ts');
const DEST = path.resolve(__dirname, '../functions/src/segmentEngine.ts');

const HEADER = `/**
 * AUTO-SYNCED — DO NOT EDIT THIS FILE DIRECTLY.
 * Source of truth: backend/src/services/reconciliation/segmentEngine.ts
 * Regenerated by scripts/sync-segment-engine.js (runs automatically as
 * \`functions\`'s \`prebuild\` step — see functions/package.json).
 */
`;

function main() {
  if (!fs.existsSync(SRC)) {
    console.error(`[sync-segment-engine] source file not found: ${SRC}`);
    process.exit(1);
  }

  const body = fs.readFileSync(SRC, 'utf8');
  fs.writeFileSync(DEST, HEADER + body, 'utf8');
  console.log(`[sync-segment-engine] synced -> ${path.relative(process.cwd(), DEST)}`);
}

main();
